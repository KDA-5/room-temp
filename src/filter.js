/**
 * 욕설·성희롱 거르기.
 *
 * 36명이 익명으로 쓰는 판이라, 한 명만 선을 넘어도 분위기가 통째로 망가집니다.
 * 그래서 올리기 전에 먼저 걸러요 — 걸리면 아예 저장이 안 됩니다.
 *
 * 우회 수법을 어느 정도 따라갑니다. 띄어쓰기·특수문자·반복 글자를 걷어내고,
 * 숫자로 바꿔 쓴 글자(s1bal, f0ck)도 되돌린 뒤에 비교해요.
 *
 * 물론 작정하고 피하려면 피할 수 있습니다. 여기서 막는 건 "욱해서 한 줄 쓰는"
 * 대부분의 경우고, 그걸 넘어선 건 신고 → 10건이면 글쓰기 잠금으로 처리합니다.
 */

/** 비교하기 전에 글자를 최대한 맨몸으로 만듭니다. */
export function normalize(text) {
  return String(text)
    .toLowerCase()
    .normalize("NFKC")
    // 공백·문장부호 제거 — "시 발", "시*발" 같은 걸 붙여놓습니다
    .replace(/[\s._\-*~^+=/\\|<>(){}\[\]'"`!?,;:#$%&]/g, "")
    // 숫자로 바꿔 쓴 글자를 되돌립니다 (s1bal → sibal, f0ck → fock)
    .replace(/0/g, "o")
    .replace(/1/g, "i")
    .replace(/3/g, "e")
    .replace(/4/g, "a")
    .replace(/@/g, "a")
    // 같은 글자 반복은 한 번으로 (시이이발 → 시이발, ㅆㅂㅂㅂ → ㅆㅂ)
    .replace(/(.)\1+/g, "$1");
}

/**
 * 막을 말들. 자모만 남긴 형태(ㅅㅂ)와 늘여 쓴 변형도 같이 넣어둡니다.
 * normalize 를 거친 뒤에 비교하므로, 여기 적힌 것도 정규화된 형태로 매칭돼요.
 */
const WORDS = [
  // 욕설
  "시발", "씨발", "시발놈", "씨발년", "ㅅㅂ", "ㅆㅂ", "ㅅㅃ", "sibal", "ssibal",
  // 늘여 쓰거나 받침을 바꾼 흔한 변형 (시이이발 → 시이발 로 줄어든 뒤 걸립니다)
  "시이발", "씨이발", "시바", "씨바", "시봘", "씨봘", "시팔", "씨팔", "쒸발", "슈발", "쓰발", "스발",
  "병신", "ㅂㅅ", "byungsin", "븅신", "빙신", "병싄",
  "지랄", "ㅈㄹ", "지럴", "ㅈㄹ하",
  "좆", "좇", "존나", "졸라", "ㅈㄴ", "ㅈ같",
  "개새끼", "새끼", "ㅅㄲ", "개색", "개세끼", "쌍놈", "쌍년", "개놈", "개년",
  "미친놈", "미친년", "또라이", "돌아이",
  "꺼져", "닥쳐", "뒤져", "뒈져", "죽어라", "죽여버",
  "엿먹", "니미", "니애미", "느금", "애미뒤",
  "fuck", "fck", "fock", "shit", "bitch", "asshole", "bullshit",
  // 비하
  "찐따", "장애인새끼", "병신새끼", "한남충", "한녀충", "김치녀", "된장녀", "맘충", "급식충", "틀딱",
  // 성적 표현
  "섹스", "ㅅㅅ하", "자위", "보지", "자지", "ㅈㅈ빨", "꼴려", "꼴리", "야동",
  "변태새끼", "몸매보", "가슴만", "강간", "성폭행",
];

const NEEDLES = WORDS.map(normalize).filter(Boolean);

/** 걸리는 말이 있으면 그 말을, 없으면 null 을 돌려줍니다. */
export function findBad(text) {
  const flat = normalize(text);
  if (!flat) return null;
  for (let i = 0; i < NEEDLES.length; i++) {
    if (flat.includes(NEEDLES[i])) return WORDS[i];
  }
  return null;
}

export const isClean = (text) => findBad(text) === null;

